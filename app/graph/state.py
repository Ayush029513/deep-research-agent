from typing import TypedDict, List, Any


class ResearchState(TypedDict, total=False):

    # =================================================
    # Input
    # =================================================

    topic: str

    # =================================================
    # Planning
    # =================================================

    research_plan: Any
    search_queries: List[str]

    # =================================================
    # Search
    # =================================================

    search_results: List[dict]

    # =================================================
    # RAG
    # =================================================

    retrieved_documents: List[Any]

    # =================================================
    # Agents
    # =================================================

    research: str
    verified: str
    report: str
    final_report: str

    # =================================================
    # Validation
    # =================================================

    citation_validation: dict